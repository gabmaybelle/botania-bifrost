package vazkii.botania.common.block;

import net.minecraft.network.chat.Component;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.TooltipFlag;
import net.minecraft.world.item.component.TooltipDisplay;
import net.minecraft.world.level.block.Block;

import java.util.function.Consumer;

/** A block item that hands the tooltip to its {@link BlockWithTooltip} block. */
public class TooltipBlockItem extends BlockItem {
	public TooltipBlockItem(Block block, Properties properties) {
		super(block, properties);
	}

	@Override
	public void appendHoverText(ItemStack stack, TooltipContext context, TooltipDisplay display, Consumer<Component> tooltip, TooltipFlag flag) {
		super.appendHoverText(stack, context, display, tooltip, flag);
		if (getBlock() instanceof BlockWithTooltip withTooltip) {
			withTooltip.appendHoverText(stack, context, display, tooltip, flag);
		}
	}
}
